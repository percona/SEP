#!/usr/bin/env bash
# Generate this harness's per-deployment secrets (.env) and render the
# settings.yaml + pmm.conf inputs from their committed templates. Idempotent:
# an existing .env is kept, templates are re-rendered on every run, and a
# Grafana token already minted into settings.yaml survives the re-render.

set -o nounset
set -o pipefail

if [[ ${DEBUG:-0} == "1" ]]; then
    set -o xtrace
fi

error() { printf '✗ %s\n' "$*" >&2; }
success() { printf '✓ %s\n' "$*" >&2; }
info() { printf 'ℹ %s\n' "$*" >&2; }

need_cmd() {
    command -v "$1" > /dev/null 2>&1 || {
        error "Missing required command: $1"
        exit 2
    }
}

need_cmd openssl
need_cmd sed

usage() {
    cat << 'EOF'
bootstrap.sh

Generate .env (PG password, SEP secret key, SEP internal token) next to this
script if it does not exist, then render settings.yaml and pmm.conf from
settings.template.yaml and pmm.conf.template. Run before the first
`docker compose up -d`, and re-run after editing a template.

Options:
  -h, --help    Show this help
EOF
    exit "${1:-0}"
}

[[ $# -eq 0 ]] || case "$1" in
    -h | --help) usage 0 ;;
    *)
        error "Unknown argument: $1"
        usage 2
        ;;
esac

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "${script_dir}" || exit 1

if [[ -f .env ]]; then
    info "Keeping existing .env"
else
    cat > .env << EOF
# Generated by bootstrap.sh — per-deployment feature-build secrets (gitignored)
SEP_PG_PASSWORD=$(openssl rand -hex 16)
SEP_SECRET_KEY=$(openssl rand -hex 32)
SEP_INTERNAL_TOKEN=$(openssl rand -hex 32)
EOF
    chmod 600 .env
    success "Generated .env"
fi

# shellcheck disable=SC1091
source .env
: "${SEP_PG_PASSWORD:?missing in .env}" "${SEP_SECRET_KEY:?missing in .env}" "${SEP_INTERNAL_TOKEN:?missing in .env}"

# Carry a previously minted Grafana token across re-renders
minted="glsa_REPLACE_ME"
if [[ -f settings.yaml ]]; then
    existing="$(sed -n 's/.*service_account_token: \(glsa_[A-Za-z0-9_]*\).*/\1/p' settings.yaml | head -1)"
    [[ -n ${existing} ]] && minted="${existing}"
fi

# Truncate-write (cat >) keeps the target inode, so a running container's bind
# mount sees the new content without a recreate
render() {
    local template="$1" target="$2"
    sed -e "s|__SEP_PG_PASSWORD__|${SEP_PG_PASSWORD}|g" \
        -e "s|__SEP_SECRET_KEY__|${SEP_SECRET_KEY}|g" \
        -e "s|__SEP_INTERNAL_TOKEN__|${SEP_INTERNAL_TOKEN}|g" \
        -e "s|__SEP_BEARER_TOKEN__|${SEP_INTERNAL_TOKEN}|g" \
        -e "s|glsa_REPLACE_ME|${minted}|g" \
        "${template}" > ".render.tmp"
    cat .render.tmp > "${target}"
    rm -f .render.tmp
    success "Rendered ${target}"
}

render settings.template.yaml settings.yaml
render pmm.conf.template pmm.conf

info "Next: docker compose up -d   (or: podman compose up -d)"
